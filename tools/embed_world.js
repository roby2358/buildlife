// Regenerates js/world_default.js from world/default_world.md.
// file:// pages can't fetch .md files, so the default world ships as a JS string (D-15).
// Usage: node tools/embed_world.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const md = fs.readFileSync(path.join(root, 'world/default_world.md'), 'utf8');
const js = `// GENERATED by tools/embed_world.js from world/default_world.md. Do not edit by hand.\n` +
  `var BL = window.BL = window.BL || {};\nBL.DEFAULT_WORLD = ${JSON.stringify(md)};\n`;
fs.writeFileSync(path.join(root, 'js/world_default.js'), js);
console.log(`js/world_default.js: ${md.length} chars`);
